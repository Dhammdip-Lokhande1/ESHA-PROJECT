def seed_everything(seed=42):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    num_cpus = os.cpu_count() or 4
    torch.set_num_threads(num_cpus)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def cached_tokenize(code_str: str):
    if code_str not in _token_cache:
        _token_cache[code_str] = tokenize_code(code_str)
    return _token_cache[code_str]


def cached_ast(code_str: str):
    if code_str not in _ast_cache:
        _ast_cache[code_str] = parse_ast(code_str)
    return _ast_cache[code_str]


def get_code_embeddings_batch(code_strs: List[str], batch_size: int = 32) -> Dict[str, np.ndarray]:
    missing = [c for c in code_strs if c not in _sem_embed_cache]
    if not missing:
        return {c: _sem_embed_cache[c] for c in code_strs}
    tokenizer, model = _load_model()
    device = "cuda" if torch.cuda.is_available() else "cpu"
    for i in range(0, len(missing), batch_size):
        batch = missing[i : i + batch_size]
        enc = tokenizer(batch, truncation=True, max_length=512, padding=True, return_tensors="pt").to(device)
        with torch.no_grad():
            out = model(**enc)
            mask = enc["attention_mask"].unsqueeze(-1)
            token_emb = out.last_hidden_state * mask
            sum_emb = token_emb.sum(dim=1)
            sum_mask = mask.sum(dim=1).clamp(min=1e-9)
            mean_emb = sum_emb / sum_mask
            norm_emb = F.normalize(mean_emb, p=2, dim=1).cpu().numpy()
        for code_str, emb in zip(batch, norm_emb):
            _sem_embed_cache[code_str] = emb
    return {c: _sem_embed_cache[c] for c in code_strs}


def get_code_embedding(code_str: str) -> np.ndarray:
    if code_str in _sem_embed_cache:
        return _sem_embed_cache[code_str]
    res = get_code_embeddings_batch([code_str], batch_size=1)
    return res[code_str]


def fast_lexical_similarity(ca: str, cb: str) -> float:
    if ca == cb:
        return 1.0
    key = (ca, cb) if ca <= cb else (cb, ca)
    if key in _lex_cache:
        return _lex_cache[key]
    ta, tb = cached_tokenize(ca), cached_tokenize(cb)
    val, _ = lexical_similarity(ta, tb)
    val = float(val) if val is not None else 0.0
    _lex_cache[key] = val
    return val


def fast_structural_similarity(ca: str, cb: str) -> float:
    if ca == cb:
        return 1.0
    key = (ca, cb) if ca <= cb else (cb, ca)
    if key in _struct_cache:
        return _struct_cache[key]
    aa, ab = cached_ast(ca), cached_ast(cb)
    if aa is None or ab is None:
        _struct_cache[key] = 0.0
        return 0.0

    # Fast-path for large ASTs to avoid O(N^2) ZSS dynamic programming freeze
    cnt_a = sum(1 for _ in ast.walk(aa))
    cnt_b = sum(1 for _ in ast.walk(ab))
    if cnt_a + cnt_b > 120:
        c_a = Counter(type(n).__name__ for n in ast.walk(aa))
        c_b = Counter(type(n).__name__ for n in ast.walk(ab))
        common = sum(min(c_a[k], c_b[k]) for k in (set(c_a) | set(c_b)))
        total = max(sum(c_a.values()), sum(c_b.values()))
        val = float(common / total) if total > 0 else 0.0
    else:
        val, _ = structural_similarity(aa, ab)
        val = float(val) if val is not None else 0.0

    _struct_cache[key] = val
    return val


def fast_semantic_similarity(ca: str, cb: str) -> float:
    if ca == cb:
        return 1.0
    ea = get_code_embedding(ca)
    eb = get_code_embedding(cb)
    cos_raw = float(np.dot(ea, eb))
    return float(max(0.0, min(1.0, cos_raw)))


def load_transbench_pairs() -> Tuple[List[Dict], List[Dict]]:
    """Loads pairs from EHSA-TransBench pairs.csv."""
    pairs_file = TRANSBENCH_DIR / "pairs.csv"
    if not pairs_file.exists():
        raise FileNotFoundError(f"TransBench pairs file not found: {pairs_file}")

    train_pairs = []
    test_pairs = []

    with open(pairs_file, mode="r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            code_a_path = TRANSBENCH_DIR / row["code_a_path"]
            code_b_path = TRANSBENCH_DIR / row["code_b_path"]

            item = {
                "pair_id": row["pair_id"],
                "split": row["split"],
                "code_a": code_a_path.read_text(encoding="utf-8"),
                "code_b": code_b_path.read_text(encoding="utf-8"),
                "label": int(row["label"]),
                "transformation_label": row["transformation_label"],
                "negative_type": row["negative_type"],
                "problem_id": row["problem_id"],
            }

            if row["split"] in ("train", "val"):
                train_pairs.append(item)
            else:
                test_pairs.append(item)

    return train_pairs, test_pairs


def select_best_threshold(y_true: np.ndarray, scores: np.ndarray) -> Tuple[float, float]:
    """Select decision threshold tau in [0.0, 1.0] maximizing F1 score on training split."""
    best_tau = 0.5
    best_f1 = -1.0
    thresholds = np.linspace(0.0, 1.0, 201)

    for tau in thresholds:
        y_pred = (scores >= tau).astype(int)
        f1 = f1_score(y_true, y_pred, zero_division=0)
        if f1 > best_f1:
            best_f1 = f1
            best_tau = tau

    return float(best_tau), float(best_f1)


def compute_map_at_r(pairs: List[Dict], score_dict: Dict[str, float]) -> float:
    """Computes MAP@R retrieval score over test set programs."""
    queries = defaultdict(list)
    for p in pairs:
        pid = p["problem_id"]
        queries[p["pair_id"]].append(p)

    aps = []
    # Evaluate code similarity ranking for test pairs
    for pid, group in queries.items():
        # group AP@R
        y_true = np.array([p["label"] for p in group])
        R = sum(y_true)
        if R == 0:
            continue
        scores = np.array([score_dict[p["pair_id"]] for p in group])
        sorted_indices = np.argsort(-scores)
        top_r_labels = y_true[sorted_indices[:R]]
        ap = sum(top_r_labels) / float(R)
        aps.append(ap)

    return float(np.mean(aps)) if aps else 0.0


def bootstrap_ci(
    y_true: np.ndarray,
    scores: np.ndarray,
    tau: float,
    problem_ids: np.ndarray,
    n_resamples: int = 1000,
    seed: int = 42,
) -> Dict[str, List[float]]:
    """Computes 95% CIs for F1 and ROC-AUC via pair-level and group-level bootstrap."""
    rng = np.random.RandomState(seed)

    pair_f1s, pair_aucs = [], []
    group_f1s, group_aucs = [], []

    n_samples = len(y_true)
    unique_groups = np.unique(problem_ids)

    for _ in range(n_resamples):
        # 1. Pair-level bootstrap
        idx_pair = rng.choice(n_samples, size=n_samples, replace=True)
        yt_p, sc_p = y_true[idx_pair], scores[idx_pair]
        yp_p = (sc_p >= tau).astype(int)
        pair_f1s.append(f1_score(yt_p, yp_p, zero_division=0))
        try:
            pair_aucs.append(roc_auc_score(yt_p, sc_p))
        except ValueError:
            pass

        # 2. Problem-group-level bootstrap
        sampled_groups = rng.choice(unique_groups, size=len(unique_groups), replace=True)
        idx_group = []
        for g in sampled_groups:
            idx_group.extend(np.where(problem_ids == g)[0])
        idx_group = np.array(idx_group)

        yt_g, sc_g = y_true[idx_group], scores[idx_group]
        yp_g = (sc_g >= tau).astype(int)
        group_f1s.append(f1_score(yt_g, yp_g, zero_division=0))
        try:
            group_aucs.append(roc_auc_score(yt_g, sc_g))
        except ValueError:
            pass

    def get_ci(arr):
        if not arr:
            return [0.0, 0.0]
        return [float(np.percentile(arr, 2.5)), float(np.percentile(arr, 97.5))]

    return {
        "f1_pair_ci": get_ci(pair_f1s),
        "auc_pair_ci": get_ci(pair_aucs),
        "f1_group_ci": get_ci(group_f1s),
        "auc_group_ci": get_ci(group_aucs),
    }


def mcnemar_test(y_true: np.ndarray, pred_ref: np.ndarray, pred_baseline: np.ndarray) -> float:
    """Computes exact McNemar test p-value comparing predictions against reference."""
    b = np.sum((pred_ref == y_true) & (pred_baseline != y_true))
    c = np.sum((pred_ref != y_true) & (pred_baseline == y_true))
    n = b + c
    if n == 0:
        return 1.0
    res = binomtest(min(b, c), n=n, p=0.5)
    return float(res.pvalue)


def run_evaluation():
    seed_everything(SEED)
    print("=" * 70)
    print("EHSA External Baselines Fair Evaluation Pipeline")
    print("=" * 70)

    train_pairs, test_pairs = load_transbench_pairs()
    print(f"Loaded EHSA-TransBench: {len(train_pairs)} Train/Val pairs, {len(test_pairs)} Test pairs.")

    # 1. Instantiate all baseline adapters
    raw_baselines = [
        ("Normalized Token", NormalizedTokenBaseline()),
        ("JPlag CLI", JPlagAdapter()),
        ("Dolos CLI", DolosAdapter()),
        ("CodeBERT Cosine", get_codebert_baseline()),
        ("GraphCodeBERT Cosine", get_graphcodebert_baseline()),
        ("UniXcoder Cosine", get_unixcoder_baseline(shared_cache=_sem_embed_cache)),
    ]

    # Add EHSA internal channels & fusions
    ehsa_methods = ["Lexical", "Structural", "Semantic", "Fixed Fusion", "Research Fusion"]

    # Filter available baselines and record skipped ones
    active_baselines = []
    skipped_baselines = []

    for name, adapter in raw_baselines:
        avail, reason = adapter.is_available()
        if avail:
            active_baselines.append((name, adapter))
            print(f"  [AVAILABLE] {name}")
        else:
            skipped_baselines.append({
                "name": name,
                "status": "Skipped",
                "reason": reason
            })
            print(f"  [SKIPPED]   {name} -> {reason}")

    # Pre-compute embeddings for all unique code snippets across EHSA-TransBench
    all_unique_codes = list(set(
        [p["code_a"] for p in train_pairs + test_pairs] +
        [p["code_b"] for p in train_pairs + test_pairs]
    ))
    print(f"\nPre-computing embeddings for {len(all_unique_codes)} unique code snippets (batch_size=32)...", flush=True)
    
    t_pre = time.time()
    get_code_embeddings_batch(all_unique_codes, batch_size=32)
    print(f"  Finished EHSA UniXcoder pre-embeddings in {time.time() - t_pre:.2f}s", flush=True)

    for name, adapter in active_baselines:
        if hasattr(adapter, "get_embeddings_batch"):
            t_adapter = time.time()
            print(f"  Pre-computing {name} embeddings...", flush=True)
            adapter.get_embeddings_batch(all_unique_codes, batch_size=32)
            print(f"  Finished {name} pre-embeddings in {time.time() - t_adapter:.2f}s", flush=True)

    # Compute EHSA channel features for train and test
    print("\nComputing EHSA feature matrices (Lexical, Structural, Semantic)...", flush=True)
    
    def extract_features(pair_list, split_name="Train"):
        X_feats = []
        y_labels = []
        p_ids = []
        total = len(pair_list)
        print(f"Extracting EHSA features for {total} {split_name} pairs...", flush=True)
        for i, p in enumerate(pair_list):
            ca, cb = p["code_a"], p["code_b"]
            l_sim = fast_lexical_similarity(ca, cb)
            s_sim = fast_structural_similarity(ca, cb)
            m_sim = fast_semantic_similarity(ca, cb)
            X_feats.append([l_sim, s_sim, m_sim])
            y_labels.append(p["label"])
            p_ids.append(p["problem_id"])
            if (i + 1) % 500 == 0 or (i + 1) == total:
                print(f"  [{split_name}] Processed {i+1}/{total} pairs...", flush=True)
        return np.array(X_feats), np.array(y_labels), np.array(p_ids)

    X_train_ehsa, y_train, pids_train = extract_features(train_pairs, "Train")
    X_test_ehsa, y_test, pids_test = extract_features(test_pairs, "Test")

    # Train Research Fusion model (Logistic Regression) on Train Split Only
    clf = LogisticRegression(random_state=SEED, max_iter=1000)
    clf.fit(X_train_ehsa, y_train)

    train_scores_map: Dict[str, np.ndarray] = {
        "Lexical": X_train_ehsa[:, 0],
        "Structural": X_train_ehsa[:, 1],
        "Semantic": X_train_ehsa[:, 2],
        "Fixed Fusion": np.mean(X_train_ehsa, axis=1),
        "Research Fusion": clf.predict_proba(X_train_ehsa)[:, 1],
    }

    test_scores_map: Dict[str, np.ndarray] = {
        "Lexical": X_test_ehsa[:, 0],
        "Structural": X_test_ehsa[:, 1],
        "Semantic": X_test_ehsa[:, 2],
        "Fixed Fusion": np.mean(X_test_ehsa, axis=1),
        "Research Fusion": clf.predict_proba(X_test_ehsa)[:, 1],
    }

    # Compute baseline scores on train & test
    for name, adapter in active_baselines:
        print(f"Computing scores for baseline: {name}...")
        t0 = time.time()

        tr_scores = np.array([adapter.score(p["code_a"], p["code_b"]) for p in train_pairs])
        te_scores = np.array([adapter.score(p["code_a"], p["code_b"]) for p in test_pairs])

        train_scores_map[name] = tr_scores
        test_scores_map[name] = te_scores
        print(f"  Finished {name} in {time.time() - t0:.2f}s")

    # 2. Train-Only Threshold Tuning & Test Metrics Computation
    print("\nTuning thresholds on Train split and evaluating on Test split...")

    eval_results = {}
    test_preds_map = {}

    all_method_names = ehsa_methods + [name for name, _ in active_baselines]

    for name in all_method_names:
        tr_sc = train_scores_map[name]
        te_sc = test_scores_map[name]

        # Tune threshold strictly on train split
        tau_star, train_f1 = select_best_threshold(y_train, tr_sc)

        # Apply tau_star to test split
        y_pred = (te_sc >= tau_star).astype(int)
        test_preds_map[name] = y_pred

        prec = precision_score(y_test, y_pred, zero_division=0)
        rec = recall_score(y_test, y_pred, zero_division=0)
        f1 = f1_score(y_test, y_pred, zero_division=0)
        acc = accuracy_score(y_test, y_pred)

        try:
            roc_auc = roc_auc_score(y_test, te_sc)
        except ValueError:
            roc_auc = 0.5

        try:
            pr_auc = average_precision_score(y_test, te_sc)
        except ValueError:
            pr_auc = 0.0

        # MAP@R
        pair_score_dict = {p["pair_id"]: float(sc) for p, sc in zip(test_pairs, te_sc)}
        map_r = compute_map_at_r(test_pairs, pair_score_dict)

        # Bootstrap CIs
        cis = bootstrap_ci(y_test, te_sc, tau_star, pids_test, n_resamples=1000, seed=SEED)

        eval_results[name] = {
            "threshold": tau_star,
            "train_f1": train_f1,
            "precision": float(prec),
            "recall": float(rec),
            "f1": float(f1),
            "accuracy": float(acc),
            "roc_auc": float(roc_auc),
            "pr_auc": float(pr_auc),
            "map_at_r": float(map_r),
            "f1_pair_ci": cis["f1_pair_ci"],
            "auc_pair_ci": cis["auc_pair_ci"],
            "f1_group_ci": cis["f1_group_ci"],
            "auc_group_ci": cis["auc_group_ci"],
        }

    # 3. Statistical Significance vs. Research Fusion (Adaptive Fusion)
    ref_preds = test_preds_map["Research Fusion"]
    ref_auc = eval_results["Research Fusion"]["roc_auc"]

    for name in all_method_names:
        mcn_p = mcnemar_test(y_test, ref_preds, test_preds_map[name])
        delta_auc = ref_auc - eval_results[name]["roc_auc"]
        eval_results[name]["mcnemar_p_value"] = float(mcn_p)
        eval_results[name]["delta_auc_vs_rf"] = float(delta_auc)

    # 4. Per-Transformation Breakdown (Recall per transformation_label)
    print("\nComputing Per-Transformation Breakdown on Test Split...")

    transformation_types = sorted(list(set(
        p["transformation_label"] for p in test_pairs if p["label"] == 1
    )))

    per_transform_recall = defaultdict(dict)

    for name in all_method_names:
        tau_star = eval_results[name]["threshold"]
        te_sc = test_scores_map[name]

        for t_label in transformation_types:
            # Positive test pairs for this transformation
            indices = [
                i for i, p in enumerate(test_pairs)
                if p["label"] == 1 and p["transformation_label"] == t_label
            ]
            if not indices:
                per_transform_recall[name][t_label] = 0.0
                continue

            sub_sc = te_sc[indices]
            sub_pred = (sub_sc >= tau_star).astype(int)
            rec_t = sum(sub_pred) / float(len(sub_pred))
            per_transform_recall[name][t_label] = float(rec_t)

    # 5. Output Results Files: metrics.json, per_transformation.csv, table.md

    # A. metrics.json
    metrics_json_path = RESULTS_DIR / "metrics.json"
    output_meta = {
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "seed": SEED,
        "n_train_pairs": len(train_pairs),
        "n_test_pairs": len(test_pairs),
        "ehsa_fusion_weights": {
            "intercept": float(clf.intercept_[0]),
            "lexical_weight": float(clf.coef_[0][0]),
            "structural_weight": float(clf.coef_[0][1]),
            "semantic_weight": float(clf.coef_[0][2]),
        },
        "methods": eval_results,
        "skipped_baselines": skipped_baselines,
        "per_transformation_recall": per_transform_recall,
    }
    metrics_json_path.write_text(json.dumps(output_meta, indent=2), encoding="utf-8")
    print(f"Saved JSON metrics to: {metrics_json_path}")

    # B. per_transformation.csv
    csv_path = RESULTS_DIR / "per_transformation.csv"
    csv_headers = ["method"] + transformation_types + ["overall_f1", "overall_auc"]
    with open(csv_path, mode="w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(csv_headers)
        for name in all_method_names:
            row = [name]
            for t_label in transformation_types:
                row.append(f"{per_transform_recall[name].get(t_label, 0.0):.4f}")
            row.append(f"{eval_results[name]['f1']:.4f}")
            row.append(f"{eval_results[name]['roc_auc']:.4f}")
            writer.writerow(row)
    print(f"Saved Per-Transformation CSV to: {csv_path}")

    # C. table.md
    md_path = RESULTS_DIR / "table.md"
    md_content = generate_markdown_report(
        all_method_names=all_method_names,
        eval_results=eval_results,
        per_transform_recall=per_transform_recall,
        transformation_types=transformation_types,
        skipped_baselines=skipped_baselines,
    )
    md_path.write_text(md_content, encoding="utf-8")
    print(f"Saved Markdown Summary Table to: {md_path}")

    print("\nEvaluation Completed Successfully!")


def generate_markdown_report(
    all_method_names: List[str],
    eval_results: Dict[str, Dict],
    per_transform_recall: Dict[str, Dict[str, float]],
    transformation_types: List[str],
    skipped_baselines: List[Dict],
) -> str:
    lines = []
    lines.append("# EHSA Baseline Comparative Benchmarking & Per-Transformation Breakdown\n")
    lines.append("## 1. Main Fair Comparative Benchmark (Train-Tuned Threshold $\\tau^*$)\n")
    lines.append("| Method | Category | $\\tau^*$ | Precision | Recall | F1 Score [95% CI] | ROC-AUC [95% CI] | PR-AUC | MAP@R | McNemar $p$ |")
    lines.append("| :--- | :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: |")

    for name in all_method_names:
        r = eval_results[name]
